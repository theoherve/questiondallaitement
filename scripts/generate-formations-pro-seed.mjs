#!/usr/bin/env node
/**
 * Generate seed_formations_pro.sql from scraped wix-formations-pro.json
 * Usage: node scripts/generate-formations-pro-seed.mjs
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const formations = JSON.parse(
  readFileSync(join(root, 'formations-scraper/wix-formations-pro.json'), 'utf8')
);

function parsePriceCents(priceStr) {
  if (!priceStr || priceStr.trim() === '') return 0;
  // "390,00 €" → 39000
  const cleaned = priceStr.replace(/[^\d,]/g, '').replace(',', '.');
  return Math.round(parseFloat(cleaned) * 100) || 0;
}

function escapeSQL(str) {
  if (!str) return '';
  return str.replace(/'/g, "''");
}

function determineEventType(location) {
  const loc = (location || '').toLowerCase();
  if (loc.includes('visio') || loc.includes('zoom') || loc.includes('ligne') || loc.includes('instagram') || loc.includes('masterclass') || loc.includes('conférence')) {
    return 'online';
  }
  return 'online'; // all scraped formations appear to be online
}

const lines = [];
lines.push('-- Seed: formations professionnelles (events) scraped from Wix');
lines.push('-- Generated by scripts/generate-formations-pro-seed.mjs');
lines.push('-- DO NOT EDIT MANUALLY');
lines.push('');

for (const f of formations) {
  const slug = escapeSQL(f.slug);
  const title = escapeSQL(f.title);
  const description = escapeSQL(f.descriptionText || f.excerpt || '');
  const eventType = determineEventType(f.location);
  const startsAt = f.startDate;
  const endsAt = f.endDate;
  const location = escapeSQL(f.location || '');
  const priceCents = parsePriceCents(f.price);
  const maxParticipants = f.capacity ? parseInt(f.capacity, 10) || 'NULL' : 'NULL';
  const mainImageUrl = f.mainImage?.url || '';

  const thumbnailUrl = escapeSQL(mainImageUrl);

  lines.push(`INSERT INTO events (consultant_id, title, slug, description, type, starts_at, ends_at, location, price_cents, currency, max_participants, thumbnail_url, is_published)`);
  lines.push(`SELECT c.id, '${title}', '${slug}', '${description}', '${eventType}', '${startsAt}'::timestamptz, '${endsAt}'::timestamptz, '${location}', ${priceCents}, 'eur', ${maxParticipants}, ${thumbnailUrl ? `'${thumbnailUrl}'` : 'NULL'}, true`);
  lines.push(`FROM consultants c WHERE c.slug = 'carole-herve'`);
  lines.push(`ON CONFLICT (slug) DO UPDATE SET title = EXCLUDED.title, description = EXCLUDED.description, starts_at = EXCLUDED.starts_at, ends_at = EXCLUDED.ends_at, location = EXCLUDED.location, price_cents = EXCLUDED.price_cents, thumbnail_url = EXCLUDED.thumbnail_url, updated_at = now();`);
  lines.push('');
}

const output = lines.join('\n');
const outPath = join(root, 'supabase/seed_formations_pro.sql');
writeFileSync(outPath, output, 'utf8');
console.log(`Written ${formations.length} events to ${outPath}`);
